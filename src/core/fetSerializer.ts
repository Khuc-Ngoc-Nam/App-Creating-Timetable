function getCampuses(project: TimetableProject): Campus[] {
  const explicit = project.settings.campuses || [];
  const fromClasses = project.classes.map((schoolClass) => schoolClass.campusName);
  const fromAssignments = project.assignments.map((assignment) => assignment.campusName);
  const names = uniqueNames([
    ...explicit.map((campus) => campus.name),
    ...fromClasses,
    ...fromAssignments,
    project.settings.institutionName
  ]);
  return names.map((name) => {
    const existing = explicit.find((campus) => campus.name === name);
    return existing || { id: name, name };
  });
}

function uniqueClasses(project: TimetableProject, assignments: Assignment[]): SchoolClass[] {
  const byKey = new Map<string, SchoolClass>();
  for (const schoolClass of project.classes) {
    if (!schoolClass.campusName || !schoolClass.name) continue;
    byKey.set(classKey(schoolClass.campusName, schoolClass.name), schoolClass);
  }
  for (const assignment of assignments) {
    const key = classKey(assignment.campusName, assignment.className);
    if (!byKey.has(key)) {
      byKey.set(key, {
        id: key,
        name: assignment.className,
        campusName: assignment.campusName,
        homeroomTeacherName: ""
      });
    }
  }
  return Array.from(byKey.values());
}

function fetClassName(project: TimetableProject, schoolClass: SchoolClass): string {
  return fetClassNameFromParts(schoolClass.campusName, schoolClass.name, getCampuses(project).length > 1);
}

function fetClassNameFromParts(campusName: string, className: string, forceCampusPrefix = true): string {
  return forceCampusPrefix ? `${campusName} - ${className}` : className;
}

function roomNameForClass(project: TimetableProject, schoolClass: SchoolClass): string {
  return `Phòng ${fetClassName(project, schoolClass)}`;
}

function classKey(campusName: string, className: string): string {
  return `${campusName}::${className}`;
}

function mergeTeachers(teachers: Teacher[], assignments: Assignment[]): Teacher[] {
  const byName = new Map<string, Teacher>();
  for (const teacher of teachers) {
    if (teacher.name.trim()) byName.set(teacher.name, teacher);
  }
  for (const assignment of assignments) {
    if (assignment.teacherName.trim() && !byName.has(assignment.teacherName)) {
      byName.set(assignment.teacherName, {
        id: assignment.teacherName,
        name: assignment.teacherName,
        campusNames: uniqueNames(assignments.filter((item) => item.teacherName === assignment.teacherName).map((item) => item.campusName)),
        morningsAfternoonsBehavior: "Unrestricted"
      });
    }
  }
  return Array.from(byName.values());
}

function warnCapacity(project: TimetableProject, assignments: Assignment[], sessionCapacity: number, warnings: string[]): void {
  const classTotals = sumBy(assignments, (assignment) => assignment.className, (assignment) => assignment.weeklyPeriods);
  for (const [className, total] of classTotals) {
    if (total > sessionCapacity) {
      warnings.push(`${className}: tổng ${total} tiết vượt sức chứa ${sessionCapacity} ô.`);
    }
  }

  const teacherSlots = sessionCapacity;
  const unavailableByTeacher = new Map(project.constraints.teacherUnavailableTimes.map((item) => [item.teacherName, item.slots.length]));
  const teacherTotals = sumBy(assignments.filter((item) => item.teacherName), (assignment) => assignment.teacherName, (assignment) => assignment.weeklyPeriods);
  for (const [teacherName, total] of teacherTotals) {
    const capacity = teacherSlots - (unavailableByTeacher.get(teacherName) || 0);
    if (total > capacity) {
      warnings.push(`${teacherName}: tổng ${total} tiết vượt số ô có thể dạy là ${capacity}.`);
    }
  }
}

function realDaysFullyUnavailable(project: TimetableProject, teacherName: string): string[] {
  const calendar = buildCalendar(project.settings);
  const unavailable = project.constraints.teacherUnavailableTimes.find((item) => item.teacherName === teacherName)?.slots || [];
  const busy = new Set(unavailable.map((slot) => `${slot.dayLabel}::${slot.periodIndex}`));
  const fullyBusy: string[] = [];

  for (let realDayIndex = 0; realDayIndex < project.settings.numberOfDays; realDayIndex += 1) {
    const dayLabels = project.settings.mode === "full-day"
      ? [calendar.dayNames[realDayIndex * 2], calendar.dayNames[realDayIndex * 2 + 1]].filter(Boolean)
      : [calendar.dayNames[realDayIndex]].filter(Boolean);
    const totalSlots = dayLabels.length * project.settings.periodsPerSession;
    let busySlots = 0;

    for (const dayLabel of dayLabels) {
      for (let periodIndex = 0; periodIndex < project.settings.periodsPerSession; periodIndex += 1) {
        if (busy.has(`${dayLabel}::${periodIndex}`)) busySlots += 1;
      }
    }

    if (totalSlots > 0 && busySlots === totalSlots) {
      fullyBusy.push(calendar.realDayNames[realDayIndex] || calendar.dayNames[realDayIndex] || `Ngày ${realDayIndex + 1}`);
    }
  }

  return fullyBusy;
}

function totalPeriodsByTeacher(assignments: Assignment[]): Map<string, number> {
  return sumBy(
    assignments.filter((assignment) => assignment.teacherName),
    (assignment) => assignment.teacherName,
    (assignment) => assignment.weeklyPeriods
  );
}

function sumBy<T>(items: T[], keyOf: (item: T) => string, valueOf: (item: T) => number): Map<string, number> {
  const totals = new Map<string, number>();
  for (const item of items) {
    const key = keyOf(item);
    totals.set(key, (totals.get(key) || 0) + valueOf(item));
  }
  return totals;
}

function uniqueNames(values: string[]): string[] {
  return Array.from(new Set(values.map((value) => value.trim()).filter(Boolean)));
}

function node(name: string, value: string, indent: number): string {
  return `${" ".repeat(indent)}<${name}>${escapeXml(value)}</${name}>`;
}

function escapeXml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

function weightPercent(weight: number): string {
  const normalized = Number.isFinite(weight) ? weight : 1;
  const percent = normalized <= 1 ? normalized * 100 : normalized;
  return trimFloat(Math.min(100, Math.max(0, percent)));
}

function trimFloat(value: number): string {
  return Number(value.toFixed(4)).toString();
}

function clampInteger(value: number, min: number, max: number): number {
  if (!Number.isFinite(value)) return min;
  return Math.max(min, Math.min(max, Math.trunc(value)));
}

function normalizeOptionalInteger(value: number | undefined): number | undefined {
  if (value === undefined || !Number.isFinite(value)) return undefined;
  return Math.trunc(value);
}

function isFlagCeremonySubject(subjectName: string): boolean {
  return normalizeVietnamese(subjectName) === "chao co";
}

function normalizeVietnamese(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "D")
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ");
}

function hourName(project: TimetableProject, periodIndex: number): string {
  return buildCalendar(project.settings).hourNames[periodIndex] || `Tiết ${periodIndex + 1}`;
}
